describe("не даёт ложных срабатываний на чужие слова", () => {
  const negative: [string, string][] = [
    ["가다", "간식을 먹어요."],
    ["가다", "시간이 없어요."],
    ["크다", "커피를 마셔요."],
    ["오다", "저와 친구는 같이 가요."],
    ["듣다", "친구들은 모두 왔어요."],
    ["묻다", "매일 물을 많이 마시다"],
    ["줄다", "친구를 도와주는 사람"],
    ["줄다", "물건을 주세요."],
    ["듣다", "친구들을 만났어요."],
    ["듣다", "방에 들어가요."],
    ["알다", "안 가요."],
    ["알다", "아시아에 갔어요."],
    ["알다", "아니요, 괜찮아요."],
    ["받다", "발을 씻어요."],
    ["입다", "이웃이 왔어요."],
    ["웃다", "우수한 학생"],
    ["보다", "본문을 읽으세요."],
  ];
  for (const [ko, text] of negative) {
    it(`${ko} не в «${text}»`, () => expect(found(ko, text)).toBe(false));
  }
});

describe("формы глаголов, которых нет в списке исключений, не создаются", () => {
  it("regular ㅂ/ㄷ/ㅅ не получают неправильных форм", () => {
    expect(conjugatedForms("입다")).toEqual([]);
    expect(conjugatedForms("받다")).toEqual([]);
    expect(conjugatedForms("웃다")).toEqual([]);
  });
  it("-하다 обрабатывается отдельно", () => {
    expect(conjugatedForms("공부하다")).toEqual([]);
  });
});
